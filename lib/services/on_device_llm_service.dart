import '../models/answer_entry.dart';

/// Abstract interface for on-device Small Language Model (SLM) inference.
/// Designed for offline edge AI execution (e.g., Gemma 2B Q4 GGUF).
abstract class OnDeviceLLM {
  /// Loads the quantized model weights from the given asset/file path.
  Future<void> load(String modelPath);

  /// Generates an advisory response using retrieval-augmented context.
  Future<String> generate(String prompt, List<AnswerEntry> context, {String? locale});

  /// Returns true if the model weights are loaded into memory and ready for inference.
  bool isReady();
}

/// Mock implementation simulating an on-device quantized SLM (e.g. Gemma 2B IT Q4).
/// Simulates 500ms model loading and 800ms offline inference delay,
/// synthesizing farmer-friendly guidance from local retrieved context.
class MockOnDeviceLLM implements OnDeviceLLM {
  bool _ready = false;
  static const String defaultModelPath = 'models/gemma-2b-it-q4.gguf';

  @override
  Future<void> load(String modelPath) async {
    // Simulate loading quantized weights into RAM
    await Future.delayed(const Duration(milliseconds: 500));
    _ready = true;
  }

  @override
  Future<String> generate(String prompt, List<AnswerEntry> context, {String? locale}) async {
    if (!_ready) {
      await load(defaultModelPath);
    }

    // Simulate edge model inference token generation delay
    await Future.delayed(const Duration(milliseconds: 800));

    if (context.isEmpty) {
      return 'I need a little more information about your crop or symptoms to provide a specific recommendation. Please consult your local Krishi Vigyan Kendra (KVK).\n\n[Generated by On-device AI - Offline Mode]';
    }

    // Detect target locale from prompt or parameter
    final detectedLocale = locale ?? _detectLocale(prompt);
    final top = context.first;

    final localizedAdvice = top.getLocalizedAnswer(detectedLocale);
    final cropName = top.crop.toUpperCase();
    final category = top.category.toUpperCase();

    final buffer = StringBuffer();
    buffer.writeln('🌾 [On-Device SLM - $cropName $category]');
    buffer.writeln('Based on verified ICAR agronomic guidance:');
    buffer.writeln();
    buffer.writeln(localizedAdvice);

    if (context.length > 1) {
      final secondary = context[1];
      buffer.writeln();
      buffer.writeln('Additional Field Precaution:');
      buffer.writeln(secondary.getLocalizedAnswer(detectedLocale));
    }

    buffer.writeln();
    buffer.writeln('Source: ${top.source} (Verified by ${top.verifiedBy})');
    buffer.writeln('[Inference executed on-device with 0 KB internet data]');

    return buffer.toString();
  }

  @override
  bool isReady() => _ready;

  /// Simple heuristic to detect if the prompt is Hindi, Bengali, or English
  String _detectLocale(String text) {
    if (RegExp(r'[\u0900-\u097F]').hasMatch(text)) {
      return 'hi';
    } else if (RegExp(r'[\u0980-\u09FF]').hasMatch(text)) {
      return 'bn';
    }
    return 'en';
  }
}
